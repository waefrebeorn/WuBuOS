#!/usr/bin/env python3
"""Generate MP3 fixtures with ffmpeg and their expected metadata from ffprobe.

ffmpeg encodes and ffprobe decodes: our code never sees either. Frame counts are exact
(`-count_frames`), so the gate can require an exact match on frames and channels and a bounded
difference on duration (container duration includes encoder delay, which frame counting does not).
"""
import json
import pathlib
import subprocess
import sys

OUT = pathlib.Path("tests/fixtures/mp3")
HDR = pathlib.Path("tests/fixtures/mp3_expect.h")

CASES = [
    # name,                    rate,  channels, args
    ("cbr128_44100_stereo",   44100, 2, ["-b:a", "128k"]),
    ("cbr64_44100_mono",      44100, 1, ["-b:a", "64k"]),
    ("cbr192_48000_stereo",   48000, 2, ["-b:a", "192k"]),
    ("vbr_44100_stereo",      44100, 2, ["-q:a", "4"]),
    ("mpeg2_22050_stereo",    22050, 2, ["-b:a", "64k"]),
]


def probe(path):
    out = subprocess.check_output([
        "ffprobe", "-v", "error", "-select_streams", "a:0", "-count_frames",
        "-show_entries", "stream=sample_rate,channels,nb_read_frames,codec_name",
        "-show_entries", "format=duration", "-of", "json", str(path)])
    j = json.loads(out)
    st = j["streams"][0]
    return {
        "codec": st.get("codec_name"),
        "rate": int(st["sample_rate"]),
        "channels": int(st["channels"]),
        "frames": int(st.get("nb_read_frames") or 0),
        "duration": float(j["format"]["duration"]),
    }


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for name, rate, ch, extra in CASES:
        path = OUT / (name + ".mp3")
        subprocess.check_call([
            "ffmpeg", "-v", "error", "-y", "-f", "lavfi",
            "-i", "sine=frequency=440:duration=1.0:sample_rate=%d" % rate,
            "-ac", str(ch), "-ar", str(rate), *extra, str(path)])
        p = probe(path)
        assert p["codec"] == "mp3", (name, p)
        assert p["rate"] == rate and p["channels"] == ch, (name, p)
        rows.append((name + ".mp3", p))
        print("wrote %s: %d Hz, %d ch, %d frames, %.3f s"
              % (name, p["rate"], p["channels"], p["frames"], p["duration"]))

    lines = [
        "/* GENERATED by tools/make_mp3_fixtures.py -- do not edit by hand.",
        " * Oracle: ffmpeg encodes, ffprobe decodes and counts frames. */",
        "#ifndef WUBU_MP3_EXPECT_H",
        "#define WUBU_MP3_EXPECT_H",
        "",
        "typedef struct {",
        "    const char *file;",
        "    int sample_rate;",
        "    int channels;",
        "    int frames;",
        "    int duration_ms;      /* ffprobe's container duration, for a bounded comparison */",
        "} WubuMp3Expect;",
        "",
        "static const WubuMp3Expect WUBU_MP3_EXPECT[] = {",
    ]
    for fname, p in rows:
        lines.append('    { "%s", %d, %d, %d, %d },' % (fname, p["rate"], p["channels"], p["frames"],
                                                       round(p["duration"] * 1000)))
    lines += [
        "};",
        "#define WUBU_MP3_CASES ((int)(sizeof(WUBU_MP3_EXPECT) / sizeof(WUBU_MP3_EXPECT[0])))",
        "",
        "#endif",
        "",
    ]
    HDR.write_text("\n".join(lines))
    print("wrote", HDR)


if __name__ == "__main__":
    sys.exit(main())
