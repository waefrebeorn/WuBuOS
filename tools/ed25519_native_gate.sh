#!/usr/bin/env bash
# ed25519_native_gate.sh -- differential gate for the opt-in OpenSSL Ed25519
# backend.  Three builds of the SAME wubu_pkg_sign_* entry points, same
# canonical 32-byte digest, ephemeral OpenSSL-generated keys:
#   native   : OpenSSL EVP_PKEY_ED25519 core, policy checks retained
#   ladder   : hardened in-repo Montgomery ladder (production default)
#   fallback : native macro on but simulated unavailable -> fail-closed ladder
# Cross-sign/verify, OpenSSL-CLI interoperability, policy provenance and every
# tamper/forgery case must agree.  No key material is written into the repo.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
WUBU_MBEDTLS_ROOT="$("$ROOT/tools/mbedtls_devroot.sh")"
export WUBU_MBEDTLS_ROOT
MB="$WUBU_MBEDTLS_ROOT/usr"
for f in "$MB/include/mbedtls/sha512.h" "$MB/include/mbedtls/bignum.h" \
         "$MB/lib/x86_64-linux-gnu/libmbedcrypto.a" /usr/include/openssl/evp.h; do
    [ -f "$f" ] || { echo "[native] missing prerequisite: $f" >&2; exit 2; }
done
ls /usr/lib/*/libcrypto.so >/dev/null 2>&1 || { echo "[native] libcrypto dev symlink missing" >&2; exit 2; }
command -v openssl >/dev/null && command -v xxd >/dev/null
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
PASS=0; FAIL=0

echo "[native] mbedTLS: $(grep -m1 MBEDTLS_VERSION_STRING "$MB/include/mbedtls/version.h" | cut -d'"' -f2)"
echo "[native] OpenSSL: $(openssl version)"

# Ephemeral keys generated by OpenSSL itself (no hardcoded key material).
openssl genpkey -algorithm ED25519 -out "$TMP/key.pem" 2>/dev/null
openssl genpkey -algorithm ED25519 -out "$TMP/other.pem" 2>/dev/null
SEED=$(openssl pkey -in "$TMP/key.pem" -text -noout \
    | awk '/^priv:/{f=1;next} /^pub:/{f=0} f{gsub(/[ :]/,"");printf "%s",$0}')
PUB=$(openssl pkey -in "$TMP/key.pem" -pubout -outform DER 2>/dev/null \
    | tail -c 32 | xxd -p -c 64 | tr -d '\n')
WRONG_PUB=$(openssl pkey -in "$TMP/other.pem" -pubout -outform DER 2>/dev/null \
    | tail -c 32 | xxd -p -c 64 | tr -d '\n')
[ "${#SEED}" -eq 64 ] && [ "${#PUB}" -eq 64 ] && [ "${#WRONG_PUB}" -eq 64 ] \
    || { echo "[native] failed to extract 32-byte keys" >&2; exit 2; }
DIG=$(printf 'wubu native eddsa canonical digest' | openssl dgst -sha256 -hex -r | awk '{print $1}')
[ "${#DIG}" -eq 64 ] || { echo "[native] bad digest" >&2; exit 2; }
printf '%s' "$DIG" | xxd -r -p > "$TMP/digest.bin"
BADDIG=$(printf 'wubu tampered canonical digest' | openssl dgst -sha256 -hex -r | awk '{print $1}')
echo "[native] keys: OpenSSL-generated, 32-byte seed/pub; digest: $DIG"

CFLAGS="-w -O1 -g -std=c11 -D_GNU_SOURCE -D_POSIX_C_SOURCE=200809L -DWUBU_HAVE_MBEDTLS -DWUBU_NO_LIBM"
INCLUDES="-I$ROOT -I$ROOT/include -I$ROOT/src -I$ROOT/src/gui -I$ROOT/src/runtime -I$ROOT/src/kernel -I$MB/include -I$ROOT/tools"
SRCS="$ROOT/src/runtime/wubu_crc32.c \
 $ROOT/src/gui/wubu_pkgmgr.c $ROOT/src/gui/wubu_pkgmgr_verify.c $ROOT/src/gui/wubu_pkg_sign.c $ROOT/src/gui/wubu_pkg_ed25519.c \
 $ROOT/src/gui/wubu_pkgmgr_revoke_feed.c \
 $ROOT/src/gui/wubu_pkgmgr_resolve.c $ROOT/src/gui/wubu_pkgmgr_manifest.c \
 $ROOT/src/gui/wubu_pkgmgr_db.c $ROOT/src/gui/wubu_pkgmgr_pkg.c \
 $ROOT/src/gui/wubu_pkgmgr_install.c $ROOT/src/gui/wubu_pkgmgr_txn.c \
 $ROOT/src/gui/wubu_pkgmgr_remote.c $ROOT/src/gui/wubu_pkgmgr_fetch.c \
 $ROOT/src/gui/wubu_settings.c $ROOT/src/gui/wubu_settings_defaults.c $ROOT/src/gui/wubu_settings_io.c \
 $ROOT/src/gui/wubu_theme.c $ROOT/tools/ed25519_native_gate.c \
 $ROOT/src/runtime/wubu_pkg.c $ROOT/src/runtime/wubu_json.c src/runtime/wubu_utf8.c $ROOT/src/runtime/wubu_palette.c \
 $ROOT/src/runtime/styx_names.c $ROOT/src/runtime/styx_enc.c $ROOT/src/runtime/styx_serve.c \
 $ROOT/src/runtime/styx_parse.c $ROOT/src/runtime/styx_fid.c $ROOT/src/runtime/styxfs_vfs.c \
 $ROOT/src/runtime/styxfs_callbacks.c $ROOT/src/runtime/styxfs_posix.c $ROOT/src/runtime/styxfs_path.c \
 $ROOT/src/runtime/styxfs_host.c $ROOT/src/runtime/styxfs_util.c \
 $ROOT/src/runtime/wubu_guest_root.c $ROOT/src/runtime/wubu_container.c \
 $ROOT/src/runtime/oci/oci_http_client.c $ROOT/src/kernel/wubu_math.c"
LINK="-L$MB/lib/x86_64-linux-gnu -lmbedtls -lmbedx509 -lmbedcrypto -Wl,-rpath,$MB/lib/x86_64-linux-gnu -lsqlite3 -lzstd -lm -lcrypto"

echo "[native] compiling native / ladder / fail-closed-fallback probes"
# shellcheck disable=SC2086
gcc $CFLAGS -DWUBU_HAVE_OPENSSL_EDDSA $INCLUDES -include "$ROOT/src/runtime/wubu_gnu_compat.h" $SRCS -o "$TMP/native" $LINK
# shellcheck disable=SC2086
gcc $CFLAGS $INCLUDES -include "$ROOT/src/runtime/wubu_gnu_compat.h" $SRCS -o "$TMP/ladder" $LINK
# shellcheck disable=SC2086
gcc $CFLAGS -DWUBU_HAVE_OPENSSL_EDDSA -DWUBU_EDDSA_FORCE_LADDER $INCLUDES -include "$ROOT/src/runtime/wubu_gnu_compat.h" $SRCS -o "$TMP/fallback" $LINK
export LD_LIBRARY_PATH="$MB/lib/x86_64-linux-gnu${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

SIG=""; OPS=""; OUT=""
sign_with() {
    local bin=$1
    OUT=$("$bin" sign "$SEED" "$PUB" "$DIG" "-")
    SIG=$(printf '%s\n' "$OUT" | sed -n 's/^SIGN=OK SIG=\([0-9a-f]*\)$/\1/p')
    OPS=$(printf '%s\n' "$OUT" | sed -n 's/^NATIVE_OPS=\([0-9]*\)$/\1/p')
}
verify_with() {
    local bin=$1 dg=$2 pk=$3 sg=$4
    OUT=$("$bin" verify "$SEED" "$pk" "$dg" "$sg")
    VER=$(printf '%s\n' "$OUT" | sed -n 's/^RESULT=\([A-Z]*\).*/\1/p')
    ERR=$(printf '%s\n' "$OUT" | sed -n 's/^RESULT=[A-Z]* ERR=\(.*\)$/\1/p')
    OPS=$(printf '%s\n' "$OUT" | sed -n 's/^NATIVE_OPS=\([0-9]*\)$/\1/p')
}
expect_sig() {
    if [ "${#SIG}" -eq 128 ]; then echo "[native] PASS  $1: signature produced (64 bytes)"; PASS=$((PASS+1));
    else echo "[native] FAIL  $1: no signature ($OUT)"; FAIL=$((FAIL+1)); fi
}
expect_ops() {
    local want=$1 label=$2
    if [ "${OPS:-0}" -eq "$want" ]; then echo "[native] PASS  $label (NATIVE_OPS=$OPS)"; PASS=$((PASS+1));
    else echo "[native] FAIL  $label (expected NATIVE_OPS=$want, got ${OPS:-?})"; FAIL=$((FAIL+1)); fi
}
expect_verify() {
    local want=$1 label=$2
    if [ "${VER:-}" = "$want" ]; then echo "[native] PASS  $label (RESULT=$VER ${ERR:+err=$ERR})"; PASS=$((PASS+1));
    else echo "[native] FAIL  $label (want RESULT=$want, got ${VER:-?}; $OUT)"; FAIL=$((FAIL+1)); fi
}
expect_err() {
    local needle=$1 label=$2
    case "$ERR" in *"$needle"*) echo "[native] PASS  $label (policy error: $ERR)"; PASS=$((PASS+1));;
      *) echo "[native] FAIL  $label (expected error containing '$needle', got: $ERR)"; FAIL=$((FAIL+1));; esac
}

# 1. Native signs; prove the native path actually executed (not a fallback).
sign_with "$TMP/native"; expect_sig "native sign"; expect_ops 1 "native backend exercised"
SIG_N=$SIG
# 2. Cross-build agreement: ladder verifies the native signature.
verify_with "$TMP/ladder" "$DIG" "$PUB" "$SIG_N"; expect_verify PASS "ladder verifies native signature"
verify_with "$TMP/fallback" "$DIG" "$PUB" "$SIG_N"; expect_verify PASS "fail-closed fallback verifies native signature"; expect_ops 0 "fallback path has 0 native ops"
# 3. Ladder signs; native core verifies it.
sign_with "$TMP/ladder"; expect_sig "ladder sign"; SIG_L=$SIG; expect_ops 0 "ladder build has 0 native ops"
verify_with "$TMP/native" "$DIG" "$PUB" "$SIG_L"; expect_verify PASS "native verifies ladder signature"; expect_ops 1 "native verify exercised"

# 4. OpenSSL CLI signs the same digest with the same OpenSSL-generated key.
openssl pkey -in "$TMP/key.pem" -pubout -out "$TMP/pub.pem" 2>/dev/null
openssl pkeyutl -sign -inkey "$TMP/key.pem" -rawin -in "$TMP/digest.bin" -out "$TMP/openssl.sig" 2>/dev/null
SIG_O=$(xxd -p -c 128 "$TMP/openssl.sig" | tr -d '\n')
[ "${#SIG_O}" -eq 128 ] || { echo "[native] FAIL openssl CLI sign" >&2; FAIL=$((FAIL+1)); }
verify_with "$TMP/native" "$DIG" "$PUB" "$SIG_O"; expect_verify PASS "OpenSSL-generated key+sig verify via native path"
verify_with "$TMP/ladder" "$DIG" "$PUB" "$SIG_O"; expect_verify PASS "OpenSSL CLI signature verifies via ladder too"

# 5. Fallback (native macro present but forced unavailable) still signs/verifies.
sign_with "$TMP/fallback"; expect_sig "fail-closed fallback sign"; SIG_F=$SIG; expect_ops 0 "fallback sign uses ladder"
[ "$SIG_F" = "$SIG_L" ] && { echo "[native] PASS  fallback output byte-identical to ladder"; PASS=$((PASS+1)); } \
    || { echo "[native] FAIL  fallback output differs from ladder"; FAIL=$((FAIL+1)); }

# 6. Tamper / forgery negatives -- must fail on every path.
# A negative control that can be a no-op is not a control: "00" + the rest of the signature is IDENTICAL
# to the original whenever the signature already starts with 00 (1 run in 256), and then the forgery
# correctly verifies and the gate reports "tampered signature accepted". Measured: the suite failed
# intermittently on exactly that, and passed on every retry. Flip a known digit and PROVE the difference.
flip_hex() {
    case "$1" in
        0) echo -n 1;; 1) echo -n 2;; 2) echo -n 3;; 3) echo -n 4;;
        4) echo -n 5;; 5) echo -n 6;; 6) echo -n 7;; 7) echo -n 8;;
        8) echo -n 9;; 9) echo -n a;; a) echo -n b;; b) echo -n c;;
        c) echo -n d;; d) echo -n e;; e) echo -n f;; f) echo -n 0;;
        *) echo -n 0;;
    esac
}
LAST="${SIG_N:127:1}"
FLIPPED=$(flip_hex "$LAST")
TAMPERED="${SIG_N:0:127}${FLIPPED}"
if [ "$TAMPERED" = "$SIG_N" ] || [ "${#TAMPERED}" -ne 128 ]; then
    echo "[rt] FAIL: could not build a tampered signature (refusing to test a no-op)" >&2
    exit 1
fi
verify_with "$TMP/native" "$DIG" "$PUB" "$TAMPERED"; expect_verify FAIL "tampered signature rejected by native"
verify_with "$TMP/ladder" "$DIG" "$PUB" "$TAMPERED"; expect_verify FAIL "tampered signature rejected by ladder"
verify_with "$TMP/native" "$DIG" "$WRONG_PUB" "$SIG_N"; expect_verify FAIL "wrong public key rejected by native"
verify_with "$TMP/ladder" "$DIG" "$WRONG_PUB" "$SIG_N"; expect_verify FAIL "wrong public key rejected by ladder"
verify_with "$TMP/native" "$BADDIG" "$PUB" "$SIG_N"; expect_verify FAIL "tampered digest rejected by native"
verify_with "$TMP/ladder" "$BADDIG" "$PUB" "$SIG_N"; expect_verify FAIL "tampered digest rejected by ladder"

# 7. Policy checks must run AROUND the native core (error provenance).
SMALL_PUB="01$(printf '00%.0s' $(seq 1 31))"
BASEPT="5866666666666666666666666666666666666666666666666666666666666666"
FORGED="$BASEPT""01$(printf '00%.0s' $(seq 1 31))"
verify_with "$TMP/native" "$DIG" "$SMALL_PUB" "$FORGED"; expect_verify FAIL "small-subgroup forgery rejected by native"
expect_err "small-subgroup" "small-subgroup policy checked before native core"
NONCANON="${SIG_N:0:64}$(printf 'ff%.0s' $(seq 1 32))"
verify_with "$TMP/native" "$DIG" "$PUB" "$NONCANON"; expect_verify FAIL "non-canonical S rejected by native"
expect_err "non-canonical" "non-canonical-S policy checked before native core"

echo "[native] SUMMARY: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ] || { echo "[native] GATE FAILED"; exit 1; }
echo "[native] ALL CHECKS PASSED -- native/ladder/fallback agree; policy retained; forgeries refused"
