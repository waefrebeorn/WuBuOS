#!/usr/bin/env python3
"""icon_bake.py -- SVG masters -> a C alpha-mask table, reproducibly.

The methodology (docs/compendium/04-roadmap/ui-excellence-methodology.md) says icons
are SVG masters baked into data, never bitmaps decoded at draw time. This is the bake.

It supports EXACTLY the SVG subset the icon set uses, and fails loudly on anything
else -- a silently skipped path is an icon that disappears in the product:

  <path d="M x y L x y ... Z">   polygons, optionally several subpaths (even-odd)
  <rect x y width height>        axis-aligned
  <polygon points="x,y ...">

Rasterisation is 4x4 supersampling per pixel into 8-bit coverage, which is the same
coverage idea as vbe_fill_rect_rounded: the icon and the chrome antialias identically.
Output: src/gui/icons/wubu_icons_data.h with WUBU_ICON_<NAME>_SZ and _MASK.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets/icons"
OUT = ROOT / "src/gui/icons/wubu_icons_data.h"
SIZE = 24
SS = 4  # supersamples per axis


def parse_paths(svg):
    shapes = []
    for m in re.finditer(r'<path[^>]*\bd="([^"]+)"', svg):
        d = m.group(1)
        if not re.fullmatch(r"[\sMLHVZmlhvz0-9.,\-]+", d):
            raise SystemExit(f"icon_bake: unsupported path syntax: {d[:60]}")
        pts, cur = [], None
        for cmd, args in re.findall(r"([MLHVZmlhvz])([^MLHVZmlhvz]*)", d):
            nums = [float(v) for v in re.findall(r"-?\d+\.?\d*", args)]
            if cmd in "Zz":
                if pts:
                    shapes.append(pts)
                pts = []
                continue
            rel = cmd.islower()
            if cmd in "HhVv":
                for v in nums:
                    x, y = cur if cur else (0.0, 0.0)
                    if cmd in "Hh":
                        x = (x + v) if rel else v
                    else:
                        y = (y + v) if rel else v
                    cur = (x, y)
                    pts.append(cur)
                continue
            for i in range(0, len(nums) - 1, 2):
                x, y = nums[i], nums[i + 1]
                if rel and cur:
                    x, y = cur[0] + x, cur[1] + y
                cur = (x, y)
                pts.append((x, y))
        if pts:
            shapes.append(pts)
    for m in re.finditer(r"<rect[^>]*>", svg):
        r = dict(re.findall(r'(\w[\w-]*)="([^"]+)"', m.group(0)))
        if "fill" in r and r["fill"] == "none":
            continue
        x, y = float(r.get("x", 0)), float(r.get("y", 0))
        w, h = float(r["width"]), float(r["height"])
        shapes.append([(x, y), (x + w, y), (x + w, y + h), (x, y + h)])
    for m in re.finditer(r'<polygon[^>]*\bpoints="([^"]+)"', svg):
        nums = [float(v) for v in re.findall(r"-?\d+\.?\d*", m.group(1))]
        shapes.append([(nums[i], nums[i + 1]) for i in range(0, len(nums) - 1, 2)])
    return shapes


def inside(shapes, x, y):
    """Even-odd across all subpaths: a hole is a second winding, which is how the
    maximise glyph is drawn (outer square + inner square)."""
    crossings = 0
    for poly in shapes:
        for i in range(len(poly)):
            x1, y1 = poly[i]
            x2, y2 = poly[(i + 1) % len(poly)]
            if (y1 > y) != (y2 > y):
                xin = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
                if x < xin:
                    crossings += 1
    return crossings % 2 == 1


def bake(svg):
    shapes = parse_paths(svg)
    if not shapes:
        raise SystemExit("icon_bake: no drawable shapes (refusing to emit a blank icon)")
    mask = []
    for py in range(SIZE):
        for px in range(SIZE):
            hits = 0
            for sy in range(SS):
                for sx in range(SS):
                    if inside(shapes, px + (sx + 0.5) / SS, py + (sy + 0.5) / SS):
                        hits += 1
            mask.append(round(255 * hits / (SS * SS)))
    return mask


def main():
    files = sorted(SRC.rglob("*.svg"))
    if not files:
        raise SystemExit("icon_bake: no SVG masters found")
    out = ["/* GENERATED by tools/icon_bake.py -- do not edit.",
           " * SVG masters live in assets/icons/. 8-bit coverage, 4x4 supersampled. */",
           "#ifndef WUBU_ICONS_DATA_H", "#define WUBU_ICONS_DATA_H", "",
           "#define WUBU_ICON_SIZE 24", ""]
    for f in files:
        name = f"{f.parent.name}_{f.stem}".upper().replace("-", "_")
        mask = bake(f.read_text())
        out.append(f"static const unsigned char wubu_icon_{name.lower()}[WUBU_ICON_SIZE*WUBU_ICON_SIZE] = {{")
        for i in range(0, len(mask), SIZE):
            out.append("    " + ",".join(f"{v:3d}" for v in mask[i:i + SIZE]) + ",")
        out.append("};")
        # ASCII preview so the bake is verifiable in a terminal, not by trusting it
        print(f"== {f.relative_to(SRC)}")
        for y in range(SIZE):
            print("   " + "".join(" .:-=+*#%@"[min(9, mask[y * SIZE + x] * 10 // 256)] for x in range(SIZE)))
    out += ["", "#endif", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(files)} icon(s))")


if __name__ == "__main__":
    main()
