#!/usr/bin/env python3
"""Generate animated-GIF fixtures and their expected frames, from Pillow.

The oracle is Pillow's own compositor -- an independent implementation that browsers agree
with. We do not compare our decoder to itself, and we do not hand-write expected pixels: each
fixture is built to exercise one disposal method, then Pillow says what every frame must look
like as RGBA.

Outputs (both committed):
  tests/fixtures/gif_anim/*.gif            real animated GIFs
  tests/fixtures/gif_anim_expect.h         per-frame FNV-1a digests + frame count + delays
"""
import os
import pathlib
from PIL import Image, ImageSequence

OUT_DIR = pathlib.Path("tests/fixtures/gif_anim")
HDR = pathlib.Path("tests/fixtures/gif_anim_expect.h")

# A frame that only covers part of the canvas, so compositing is actually tested.
CASES = [
    # name,   disposal, frames, canvas, transparent index
    ("dispose0", 0, 3, (40, 30)),
    ("dispose1", 1, 3, (40, 30)),
    ("dispose2", 2, 3, (40, 30)),
    ("dispose3", 3, 3, (40, 30)),
    ("interlaced", 1, 2, (48, 36)),
]


def fnv1a64(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def build(name, disposal, nframes, size, interlace=False):
    w, h = size
    frames = []
    for i in range(nframes):
        im = Image.new("P", size, color=0)
        pal = []
        # frame 0: full canvas; later frames: a smaller rect that MOVES, so disposal matters
        for r in range(16):
            pal += [r * 16, 255 - r * 16, (r * 37) % 256]
        pal += [0, 0, 0] * (256 - 16)
        im.putpalette(pal)
        if i == 0:
            box = (0, 0, w, h)
        else:
            box = (4 + i * 6, 3 + i * 4, min(w, 4 + i * 6 + 18), min(h, 3 + i * 4 + 12))
        for y in range(box[1], box[3]):
            for x in range(box[0], box[2]):
                im.putpixel((x, y), 1 + ((x + y + i) % 14))
        frames.append(im)

    path = OUT_DIR / ("%s.gif" % name)
    frames[0].save(
        path, save_all=True, append_images=frames[1:], duration=[100, 200, 300][:nframes],
        loop=0, disposal=disposal, interlace=interlace, transparency=0, optimize=False,
    )
    return path


def expected(path):
    """What Pillow says each frame looks like, composited, as RGBA bytes."""
    frames, delays = [], []
    with Image.open(path) as im:
        for fr in ImageSequence.Iterator(im):
            frames.append(fr.convert("RGBA").tobytes())
            delays.append(fr.info.get("duration", 0))
    return frames, delays


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for case in CASES:
        name, disposal, nframes, size = case[0], case[1], case[2], case[3]
        interlace = name == "interlaced"
        path = build(name, disposal, nframes, size, interlace)
        frames, delays = expected(path)
        assert len(frames) == nframes, "%s: Pillow saw %d frames, expected %d" % (name, len(frames), nframes)
        digests = [fnv1a64(f) for f in frames]
        w, h = Image.open(path).size
        rows.append((path.name, len(frames), delays, digests, w, h, disposal))

    lines = [
        "/* GENERATED by tools/make_gif_oracle.py -- do not edit by hand.",
        " * Oracle: Pillow's compositor. Each fixture exercises ONE disposal method; the digests are",
        " * FNV-1a 64 over the frame's RGBA bytes as Pillow composites them. */",
        "#ifndef WUBU_GIF_ANIM_EXPECT_H",
        "#define WUBU_GIF_ANIM_EXPECT_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    const char *file;",
        "    int frames;",
        "    int width, height;",
        "    int disposal;",
        "    int delay_ms[4];",
        "    uint64_t digest[4];",
        "} WubuGifAnimExpect;",
        "",
        "static const WubuGifAnimExpect WUBU_GIF_ANIM_EXPECT[] = {",
    ]
    for name, n, delays, digests, w, h, disposal in rows:
        d = list(delays) + [0] * (4 - len(delays))
        g = list(digests) + [0] * (4 - len(digests))
        lines.append('    { "%s", %d, %d, %d, %d, {%d, %d, %d, %d},' % (name, n, w, h, disposal, *d))
        lines.append('      { 0x%016XULL, 0x%016XULL, 0x%016XULL, 0x%016XULL } },' % tuple(g))
    lines += [
        "};",
        "#define WUBU_GIF_ANIM_CASES ((int)(sizeof(WUBU_GIF_ANIM_EXPECT) / sizeof(WUBU_GIF_ANIM_EXPECT[0])))",
        "",
        "#endif",
        "",
    ]
    HDR.write_text("\n".join(lines))
    print("wrote %d fixtures and %s" % (len(rows), HDR))


if __name__ == "__main__":
    main()
