#!/usr/bin/env python3
"""Generate whole-string expectations for the runtime text face, using FreeType via Pillow.

A per-glyph gate can be entirely green while strings are laid out wrongly: advances rounded per
glyph, bearings ignored, pen not carried across glyphs. So this fixture records what a string must
occupy -- total advance and total ink -- at several ppem, and the C test compares a composed line
against it.

Ink is compared as a SUM, not a per-pixel map: FreeType hints (grid-fits stems) and we deliberately
do not, so pixel equality is unattainable and a per-pixel diff would fail forever. The mass band is
measured from actual output; see the test source for the observed spread.

Usage: make_text_strings_oracle.py [font.ttf] [ppem,ppem,...] > tests/fixtures/<name>.h
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "third_party/fonts/selawik.ttf"
PPEMS = [int(x) for x in (sys.argv[2] if len(sys.argv) > 2 else "13,20,26,28").split(",")]

STRINGS = [
    "WubuOS",
    "Settings",
    "Control Panel",
    "ii",
    "WW",
    "Hello, Wubu",
    # Long lines are where per-glyph rounding drifts: if advances were rounded to whole pixels and
    # summed, a 44-character line would land several pixels short of FreeType.
    "The quick brown fox jumps over the lazy dog",
    "iiiiiiiiiiiiiiiiiiii",
]


def main():
    out = sys.stdout
    out.write("/* GENERATED by tools/make_text_strings_oracle.py -- do not edit by hand.\n")
    out.write(" * face: %s\n" % FONT)
    out.write(" * advance: Pillow getlength (FreeType, fractional). mass: sum of the L-mode mask,\n")
    out.write(" * i.e. coverage in 0..255 units, so it is directly comparable to a summed 8-bit alpha.\n")
    out.write(" */\n")
    out.write("#ifndef WUBU_TTF_STRINGS_ORACLE_H\n#define WUBU_TTF_STRINGS_ORACLE_H\n\n")
    out.write('#define TTF_STRINGS_PATH "%s"\n\n' % FONT)
    out.write("typedef struct {\n    const char *text;\n    int ppem;\n    double advance;\n    int mass;\n} TtfStringRow;\n\n")

    rows = []
    for ppem in PPEMS:
        font = ImageFont.truetype(FONT, ppem)
        for s in STRINGS:
            adv = font.getlength(s)
            # Render on a generous canvas: the mask must not clip, or the mass is a lie.
            pad = ppem * 2
            w = int(adv) + 2 * pad + 4
            h = ppem * 3
            img = Image.new("L", (w, h), 0)
            d = ImageDraw.Draw(img)
            d.text((pad, ppem), s, fill=255, font=font)
            mass = int(sum(img.tobytes()))
            rows.append((s, ppem, adv, mass))

    out.write("static const TtfStringRow g_ttf_strings[] = {\n")
    for s, ppem, adv, mass in rows:
        out.write('    { "%s", %d, %.3f, %d },\n' % (s.replace('"', '\\"'), ppem, adv, mass))
    out.write("};\n\n")
    out.write("#define TTF_STRINGS_COUNT (int)(sizeof(g_ttf_strings) / sizeof(g_ttf_strings[0]))\n\n")
    out.write("#endif\n")


if __name__ == "__main__":
    main()
