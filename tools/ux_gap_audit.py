#!/usr/bin/env python3
"""ux_gap_audit.py — find UX that only looks like UX.

The failure mode this exists to prevent: a menu that opens, a button that
highlights, a dialog that renders — and nothing behind it. A screenshot proves
a window; it does not prove an action.

Heuristics (evidence, not judgement):
  STUB     marker words in a GUI/app source: TODO, FIXME, stub, placeholder,
           "not implemented", "unimplemented"
  EMPTY    a function body with no statements (`{ }` or `{` newline `}`)
  UNTESTED the file is not referenced by any target in mk/tests.mk

A file with none of these is "unflagged" — not proven good, just not caught by
these three checks. The registry keeps that distinction explicit.

Usage:
  python3 tools/ux_gap_audit.py                 # markdown to stdout
  python3 tools/ux_gap_audit.py --json          # machine-readable
  python3 tools/ux_gap_audit.py --write         # write docs/UX-GAP-REGISTRY.md
"""
import argparse
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = ["src/gui", "src/apps"]
TESTS_MK = os.path.join(ROOT, "mk", "tests.mk")
OUT_MD = os.path.join(ROOT, "docs", "UX-GAP-REGISTRY.md")

MARKER = re.compile(r"\b(FIXME|stub|placeholder|not implemented|unimplemented|no-op)\b", re.I)
EMPTY_ONE = re.compile(r"\)\s*\{\s*\}")
EMPTY_MULTI = re.compile(r"\)\s*\n\{\s*\n\}")


def sources():
    for d in DIRS:
        p = os.path.join(ROOT, d)
        if not os.path.isdir(p):
            continue
        for name in sorted(os.listdir(p)):
            if name.endswith(".c"):
                yield d, os.path.join(p, name)


def test_index():
    try:
        text = open(TESTS_MK, errors="replace").read()
    except OSError:
        return lambda rel: False
    return lambda rel: rel in text or os.path.basename(rel) in text


def scan():
    covered = test_index()
    rows = []
    for d, path in sources():
        rel = os.path.relpath(path, ROOT)
        try:
            lines = open(path, errors="replace").read().splitlines()
        except OSError:
            continue
        markers, empties = [], []
        for i, line in enumerate(lines, 1):
            if line.lstrip().startswith("#include"):
                continue
            if MARKER.search(line):
                markers.append((i, line.strip()[:140]))
        text = "\n".join(lines)
        for m in EMPTY_ONE.finditer(text):
            ln = text[:m.start()].count("\n") + 1
            empties.append((ln, "empty body"))
        for m in EMPTY_MULTI.finditer(text):
            ln = text[:m.start()].count("\n") + 1
            empties.append((ln, "empty body"))
        rows.append({
            "file": rel,
            "dir": d,
            "lines": len(lines),
            "shipped": "_test" not in os.path.basename(rel),
            "stub_markers": len(markers),
            "empty_bodies": len(empties),
            "tested": bool(covered(rel)),
            "evidence": [f"L{n}: {t}" for n, t in markers[:4]] +
                        [f"L{n}: {t}" for n, t in empties[:3]],
        })
    return rows


def summarize(rows):
    ship = [r for r in rows if r["shipped"]]
    return {
        "files": len(rows),
        "shipped": len(ship),
        "stub_markers": sum(r["stub_markers"] for r in ship),
        "empty_bodies": sum(r["empty_bodies"] for r in ship),
        "untested": sum(1 for r in ship if not r["tested"]),
        "flagged": sum(1 for r in ship if r["stub_markers"] or r["empty_bodies"]),
        "test_scaffolding": len(rows) - len(ship),
        "lines": sum(r["lines"] for r in ship),
    }


def to_markdown(rows):
    s = summarize(rows)
    out = []
    out.append("# UX gap registry — generated\n")
    out.append("Generated by `tools/ux_gap_audit.py`. Re-run it; do not hand-edit.\n")
    out.append("**These are heuristics, not proof.** A clean file is *unflagged*, "
               "not verified. A flagged file is not necessarily fake — but it "
               "owes an explanation.\n")
    out.append(f"- shipped surfaces scanned: **{s['shipped']}** files, {s['lines']:,} lines\n"
               f"- test scaffolding files (excluded from counts): **{s['test_scaffolding']}**\n"
               f"- stub markers in shipped code: **{s['stub_markers']}**\n"
               f"- empty function bodies in shipped code: **{s['empty_bodies']}**\n"
               f"- shipped files with no test-target reference: **{s['untested']}**\n"
               f"- shipped files flagged by either heuristic: **{s['flagged']}**\n")
    out.append("## Flagged shipped surfaces\n")
    out.append("| File | Lines | Stubs | Empty | Tested | First evidence |")
    out.append("|---|---:|---:|---:|:--:|---|")
    flagged = [r for r in rows if r["shipped"] and (r["stub_markers"] or r["empty_bodies"])]
    flagged.sort(key=lambda r: (-(r["stub_markers"] + r["empty_bodies"]), r["file"]))
    for r in flagged:
        ev = r["evidence"][0] if r["evidence"] else ""
        ev = ev.replace("|", "\\|")
        out.append(f"| `{r['file']}` | {r['lines']} | {r['stub_markers']} | "
                   f"{r['empty_bodies']} | {'yes' if r['tested'] else 'NO'} | {ev} |")
    out.append("\n## Untested surfaces (no mk/tests.mk reference)\n")
    for r in [x for x in rows if not x["tested"]][:80]:
        out.append(f"- `{r['file']}` ({r['lines']} lines)")
    out.append("\n## What a clean entry still needs\n")
    out.append("1. An entry point reachable from the shell (not only from a test).")
    out.append("2. A test that asserts the *effect*, not the render.")
    out.append("3. A named failure mode: what the user sees when it fails.")
    out.append("4. A maintenance obligation: which test fails if this rots.")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    rows = scan()
    if args.json:
        print(json.dumps({"summary": summarize(rows), "files": rows}, indent=1))
        return
    md = to_markdown(rows)
    if args.write:
        with open(OUT_MD, "w") as f:
            f.write(md)
        print(f"wrote {OUT_MD}")
    else:
        print(md)


if __name__ == "__main__":
    main()