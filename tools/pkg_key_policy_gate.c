/* pkg_key_policy_gate.c -- opt-in differential gate harness.
 *
 * Built only by tools/pkg_key_policy_gate.sh with WUBU_HAVE_MBEDTLS. Two
 * invocations share one on-disk pkgmgr DB:
 *   record: exercise admin rotation, M-of-N feed quorum, signed expiry and
 *           escrow recovery, asserting every refusal leaves state unchanged;
 *   check:  a FRESH process proves the recovered admin, quorum/escrow policy
 *           and expiry all reloaded from the DB, then proves un-expiring.
 *
 * Every negative control re-implements the PRE-change policy verbatim
 * (TOFU bootstrap with no rotation, single-admin feed import, unsigned
 * expiry setter) so a refusal is caused by the new policy -- not by a broken
 * signature or a bad package.
 * All Ed25519 keys are ephemeral (generated by the shell driver).
 */
#include "wubu_pkgmgr.h"
#include "wubu_pkgmgr_internal.h"
#include "wubu_pkg_sign.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

static int fails = 0, passes = 0;

static int expect(const char *label, bool got, bool want) {
    bool p = (got == want);
    printf("[gate] %-62s %s (got %s, want %s)\n", label,
           p ? "PASS" : "FAIL", got ? "true" : "false", want ? "true" : "false");
    if (p) passes++; else fails++;
    return p ? 1 : 0;
}
static int yes(const char *label, bool got) { return expect(label, got, true); }
static int no(const char *label, bool got)  { return expect(label, got, false); }

static void bytes_to_hex(const uint8_t *b, size_t n, char *out) {
    static const char d[] = "0123456789abcdef";
    for (size_t i = 0; i < n; i++) {
        out[2 * i]     = d[b[i] >> 4];
        out[2 * i + 1] = d[b[i] & 0x0f];
    }
    out[2 * n] = '\0';
}

static uint8_t *slurp(const char *path, size_t *len) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }
    long n = ftell(f);
    rewind(f);
    if (n <= 0 || (size_t)n > WUBU_PKGMGR_FEED_MAX_BYTES) { fclose(f); return NULL; }
    uint8_t *buf = (uint8_t *)malloc((size_t)n);
    if (!buf) { fclose(f); return NULL; }
    if (fread(buf, 1, (size_t)n, f) != (size_t)n) { free(buf); fclose(f); return NULL; }
    fclose(f);
    *len = (size_t)n;
    return buf;
}

static bool sign_command(const char *cmd, const char *seed, char *out, size_t outsz) {
    uint8_t sig[WUBU_PKG_SIGNATURE_LEN];
    char err[256];
    if (outsz < 2 * WUBU_PKG_SIGNATURE_LEN + 1) return false;
    if (!wubu_pkg_sign_command(cmd, seed, sig, err, sizeof(err))) return false;
    bytes_to_hex(sig, WUBU_PKG_SIGNATURE_LEN, out);
    return true;
}

static bool sign_feed_file(const char *path, const char *seed, char *out, size_t outsz) {
    size_t len = 0;
    uint8_t *data = slurp(path, &len);
    if (!data) return false;
    uint8_t sig[WUBU_PKG_SIGNATURE_LEN];
    char err[256];
    bool ok = wubu_pkg_sign_bytes(data, len, WUBU_PKG_REVOCATION_FEED_DOMAIN,
                                  seed, sig, err, sizeof(err));
    free(data);
    if (!ok || outsz < 2 * WUBU_PKG_SIGNATURE_LEN + 1) return false;
    bytes_to_hex(sig, WUBU_PKG_SIGNATURE_LEN, out);
    return true;
}

static bool sign_expiry(const char *key, int64_t exp, const char *seed,
                        char *out, size_t outsz) {
    char cmd[256];
    if (!wubu_pkgmgr_anchor_expiry_command_string(key, exp, cmd, sizeof(cmd)))
        return false;
    return sign_command(cmd, seed, out, outsz);
}

/* PRE-change expiry setter: raw, unauthenticated DB write. Reproduces the
 * legacy behavior verbatim so the refusal of the new authorized setter is
 * attributable to the policy, not to a broken key or package. */
static bool legacy_set_expiry(const char *key, int64_t exp) {
    return wubu_pkgmgr_anchor_set_expiry_raw(key, exp);
}

/* PRE-change single-admin feed verifier: verifies the exact feed bytes with
 * the current admin key directly, bypassing the now-global quorum policy. */
static bool legacy_single_admin_feed_ok(const char *path, const char *admin_pub,
                                        const char *sig_hex) {
    size_t len = 0;
    uint8_t *data = slurp(path, &len);
    if (!data) return false;
    uint8_t sig[WUBU_PKG_SIGNATURE_LEN];
    bool ok = false;
    static const char digits[] = "0123456789abcdef";
    if (strlen(sig_hex) == 2 * WUBU_PKG_SIGNATURE_LEN) {
        for (size_t i = 0; i < WUBU_PKG_SIGNATURE_LEN; i++) {
            const char *a = strchr(digits, sig_hex[2 * i]);
            const char *b = strchr(digits, sig_hex[2 * i + 1]);
            if (!a || !b) { ok = false; break; }
            sig[i] = (uint8_t)(((a - digits) << 4) | (b - digits));
            ok = true;
        }
    }
    if (ok) {
        char e[256];
        ok = wubu_pkg_verify_bytes(data, len, WUBU_PKG_REVOCATION_FEED_DOMAIN,
                                   admin_pub, sig, e, sizeof(e));
    }
    free(data);
    return ok;
}

static bool write_feed(const char *path, const char *op, const char *key) {
    FILE *f = fopen(path, "w");
    if (!f) return false;
    fprintf(f, "{\"op\":\"%s\",\"key\":\"%s\"}\n", op, key);
    return fclose(f) == 0;
}

/* PRE-change expiry-blind verifier, verbatim from install.c before this leg. */
static bool legacy_verify_against_repos(const char *pkg) {
    for (int i = 0; i < g_pkgmgr.n_repos; i++)
        if (g_pkgmgr.repos[i].enabled && g_pkgmgr.repos[i].pubkey[0] &&
            wubu_pkgmgr_verify_package(pkg, g_pkgmgr.repos[i].pubkey))
            return true;
    return false;
}

static void set_anchor(const char *pub) {
    memset(g_pkgmgr.repos, 0, sizeof(g_pkgmgr.repos));
    g_pkgmgr.n_repos = 1;
    g_pkgmgr.repos[0].enabled = true;
    snprintf(g_pkgmgr.repos[0].pubkey, sizeof(g_pkgmgr.repos[0].pubkey), "%s", pub);
}

static void gate_manifest(wubu_pkg_manifest_t *m) {
    memset(m, 0, sizeof(*m));
    snprintf(m->id, sizeof(m->id), "policy-gate");
    snprintf(m->name, sizeof(m->name), "Key Policy Gate App");
    snprintf(m->version, sizeof(m->version), "1.0.0");
    snprintf(m->description, sizeof(m->description), "key policy differential gate");
    m->arch = WUBU_PKG_ARCH_X86_64;
    m->payload_type = WUBU_PKG_PAYLOAD_DATA;
    snprintf(m->sandbox_profile, sizeof(m->sandbox_profile), "default");
    snprintf(m->files[0].src, sizeof(m->files[0].src), "payload.txt");
    snprintf(m->files[0].dst, sizeof(m->files[0].dst), "payload.txt");
    m->files[0].mode = 0644;
    m->n_files = 1;
}

static bool init_cfg(const char *dbdir) {
    wubu_pkgmgr_config_t cfg;
    wubu_pkgmgr_get_default_config(&cfg);
    snprintf(cfg.db_path, sizeof(cfg.db_path), "%s", dbdir);
    snprintf(cfg.cache_dir, sizeof(cfg.cache_dir), "%s/cache", dbdir);
    snprintf(cfg.install_prefix, sizeof(cfg.install_prefix), "%s/install", dbdir);
    snprintf(cfg.repo_config_dir, sizeof(cfg.repo_config_dir), "%s/repos", dbdir);
    /* Keep verify_signatures=true (the default): the install gate must
     * actually reach wubu_pkgmgr_verify_against_repos(). */
    return wubu_pkgmgr_init(&cfg);
}

static bool admin_is(const char *want) {
    char cur[65];
    return wubu_pkgmgr_key_admin_pubkey(cur, sizeof(cur)) && strcmp(cur, want) == 0;
}

int main(int argc, char **argv) {
    /* mode dbdir pkg srcdir sign_seed sign_pub wrong_seed wrong_pub
     * admin_seed admin_pub new_admin_seed new_admin_pub
     * q1_seed q1_pub q2_seed q2_pub target rec_seed rec_pub */
    if (argc < 20) {
        fprintf(stderr, "usage: %s <record|check> <dbdir> <pkg> <srcdir> "
                        "<sign_seed> <sign_pub> <wrong_seed> <wrong_pub> "
                        "<admin_seed> <admin_pub> <new_admin_seed> <new_admin_pub> "
                        "<q1_seed> <q1_pub> <q2_seed> <q2_pub> <target> "
                        "<rec_seed> <rec_pub>\n", argv[0]);
        return 2;
    }
    const char *mode = argv[1], *dbdir = argv[2], *pkg = argv[3], *srcdir = argv[4];
    const char *sign_seed = argv[5], *sign_pub = argv[6];
    const char *wrong_seed = argv[7], *wrong_pub = argv[8];
    const char *admin_seed = argv[9], *admin_pub = argv[10];
    const char *new_seed = argv[11], *new_pub = argv[12];
    const char *q1_seed = argv[13], *q1_pub = argv[14];
    const char *q2_seed = argv[15], *q2_pub = argv[16], *target = argv[17];
    const char *rec_seed = argv[18], *rec_pub = argv[19];

    if (!init_cfg(dbdir)) {
        fprintf(stderr, "[gate] FAIL: pkgmgr init\n");
        return 1;
    }

    char cmd[1024], sig[129];
    static wubu_pkg_manifest_t m;
    gate_manifest(&m);

    if (strcmp(mode, "record") == 0) {
        /* ---------------- 1. Supported admin rotation / recovery -------- */
        printf("[gate] --- admin rotation / recovery ---\n");
        yes("bootstrap current admin key", wubu_pkgmgr_key_admin_bootstrap(admin_pub));
        yes("admin key persisted", admin_is(admin_pub));
        /* NEGATIVE CONTROL: pre-change TOFU refused every different key --
         * there was no recovery API at all. */
        no("pre-change re-bootstrap refuses new key (no recovery)",
           wubu_pkgmgr_key_admin_bootstrap(new_pub));
        yes("admin unchanged after refused re-bootstrap", admin_is(admin_pub));

        yes("rotation command string built",
            wubu_pkgmgr_key_rotate_command_string(new_pub, cmd, sizeof(cmd)));
        no("unsigned rotation refused", wubu_pkgmgr_key_admin_rotate(new_pub, NULL));
        yes("sign rotation with WRONG key", sign_command(cmd, wrong_seed, sig, sizeof(sig)));
        no("wrong-key rotation refused", wubu_pkgmgr_key_admin_rotate(new_pub, sig));
        yes("admin unchanged after unsigned/wrong-key attempts", admin_is(admin_pub));

        yes("sign rotation with current admin", sign_command(cmd, admin_seed, sig, sizeof(sig)));
        yes("signed rotation by current admin succeeds",
            wubu_pkgmgr_key_admin_rotate(new_pub, sig));
        yes("admin key is now the new key", admin_is(new_pub));
        printf("[gate] ADMIN after rotation: %s\n", new_pub);

        yes("revoke command string built",
            wubu_pkgmgr_key_command_string("revoke", target, cmd, sizeof(cmd)));
        yes("sign revoke with OLD admin key", sign_command(cmd, admin_seed, sig, sizeof(sig)));
        no("old admin key no longer authorizes after rotation",
           wubu_pkgmgr_key_revoke_authorized(target, sig));
        no("old-key revoke left no revocation", wubu_pkgmgr_key_is_revoked(target));

        yes("sign revoke with NEW admin key", sign_command(cmd, new_seed, sig, sizeof(sig)));
        yes("new admin key authorizes", wubu_pkgmgr_key_revoke_authorized(target, sig));
        yes("target revoked by new admin", wubu_pkgmgr_key_is_revoked(target));
        yes("build unrevoke command",
            wubu_pkgmgr_key_command_string("unrevoke", target, cmd, sizeof(cmd)));
        yes("sign unrevoke with new admin",
            sign_command(cmd, new_seed, sig, sizeof(sig)));
        yes("new admin unrevoke restores state",
            wubu_pkgmgr_key_unrevoke_authorized(target, sig));
        no("target unrevoked again", wubu_pkgmgr_key_is_revoked(target));

        /* ---------------- 2. M-of-N quorum feed apply ------------------- */
        printf("[gate] --- M-of-N quorum feed apply ---\n");
        const char *members[2] = { q1_pub, q2_pub };
        yes("quorum command string built",
            wubu_pkgmgr_key_quorum_command_string(2, 2, members, cmd, sizeof(cmd)));
        no("3-of-2 (M>N) command rejected",
           wubu_pkgmgr_key_quorum_command_string(3, 2, members, cmd, sizeof(cmd)));
        no("duplicate-member quorum rejected",
           wubu_pkgmgr_key_quorum_command_string(1, 2, (const char *[]){q1_pub, q1_pub},
                                                 cmd, sizeof(cmd)));
        yes("rebuild valid quorum command",
            wubu_pkgmgr_key_quorum_command_string(2, 2, members, cmd, sizeof(cmd)));
        yes("sign valid quorum config", sign_command(cmd, new_seed, sig, sizeof(sig)));
        yes("configure 2-of-2 quorum",
            wubu_pkgmgr_key_quorum_configure(2, 2, members, sig));
        int qm = 0, qn = 0;
        yes("quorum status is 2-of-2",
            wubu_pkgmgr_key_quorum_status(&qm, &qn) && qm == 2 && qn == 2);

        char feedp[512];
        snprintf(feedp, sizeof(feedp), "%s/quorum.feed", dbdir);
        yes("write feed revoking target", write_feed(feedp, "revoke", target));
        char s1[129], s2[129];
        yes("sign feed with member 1", sign_feed_file(feedp, q1_seed, s1, sizeof(s1)));
        yes("sign feed with member 2", sign_feed_file(feedp, q2_seed, s2, sizeof(s2)));
        size_t applied = 99;
        char err[256];
        const char *one[1] = { s1 };
        no("1-of-2 quorum REFUSED",
           wubu_pkgmgr_key_feed_import_quorum(feedp, one, 1, &applied, err, sizeof(err)));
        no("1-of-2 left target unrevoked", wubu_pkgmgr_key_is_revoked(target));
        yes("1-of-2 reported zero applied", applied == 0);

        const char *two[2] = { s1, s2 };
        yes("2-of-2 quorum ACCEPTED with all-or-nothing apply",
            wubu_pkgmgr_key_feed_import_quorum(feedp, two, 2, &applied, err, sizeof(err)));
        yes("2-of-2 applied exactly one entry", applied == 1);
        yes("2-of-2 revoked target", wubu_pkgmgr_key_is_revoked(target));
        yes("build unrevoke command after quorum apply",
            wubu_pkgmgr_key_command_string("unrevoke", target, cmd, sizeof(cmd)));
        yes("sign unrevoke with new admin", sign_command(cmd, new_seed, sig, sizeof(sig)));
        yes("restore target to clean state", wubu_pkgmgr_key_unrevoke_authorized(target, sig));

        /* Tamper a signature: one valid + one corrupted must be refused. */
        char bad[129];
        snprintf(bad, sizeof(bad), "%s", s2);
        bad[10] = (bad[10] == '0') ? '1' : '0';
        const char *tampered[2] = { s1, bad };
        no("tampered signature refused",
           wubu_pkgmgr_key_feed_import_quorum(feedp, tampered, 2,
                                              &applied, err, sizeof(err)));
        no("tampered signature left no revocation", wubu_pkgmgr_key_is_revoked(target));
        yes("tampered signature reported zero applied", applied == 0);

        /* NEGATIVE CONTROL: the PRE-change single-admin feed path still
         * accepts an admin-only signature (verified directly through the
         * crypto leaf), while BOTH new entry points -- including the legacy
         * single-signature wrapper -- refuse it under the configured 2-of-2
         * quorum. The bypass is closed in the policy, not by a broken key. */
        yes("sign feed with admin only (NOT a quorum member)",
            sign_feed_file(feedp, new_seed, s1, sizeof(s1)));
        const char *admin_only[1] = { s1 };
        yes("pre-change single-admin verifier ACCEPTS it (negative control)",
            legacy_single_admin_feed_ok(feedp, new_pub, s1));
        no("global policy REFUSES same sig via legacy wrapper",
           wubu_pkgmgr_key_feed_import(feedp, s1, &applied, err, sizeof(err)));
        no("new quorum policy REFUSES the same single signature",
           wubu_pkgmgr_key_feed_import_quorum(feedp, admin_only, 1,
                                              &applied, err, sizeof(err)));
        no("negative-control admin import left target unrevoked",
           wubu_pkgmgr_key_is_revoked(target));
        yes("reported zero applied on refused single sig", applied == 0);
        yes("build unrevoke after negative control",
            wubu_pkgmgr_key_command_string("unrevoke", target, cmd, sizeof(cmd)));
        yes("sign unrevoke after negative control",
            sign_command(cmd, new_seed, sig, sizeof(sig)));
        yes("clean target after negative control",
            wubu_pkgmgr_key_unrevoke_authorized(target, sig));

        /* ---------------- 3. Trust-anchor expiry ----------------------- */
        printf("[gate] --- trust-anchor expiry ---\n");
        yes("create signed package",
            wubu_pkgmgr_create_package(srcdir, pkg, &m, sign_seed));
        yes("package verifies raw with genuine key",
            wubu_pkgmgr_verify_package(pkg, sign_pub));
        no("package does not verify with wrong key",
            wubu_pkgmgr_verify_package(pkg, wrong_pub));
        set_anchor(sign_pub);

        time_t now = time(NULL);
        int64_t got_exp_probe = 0;
        /* Unsigned expiry is refused and leaves NO metadata behind. */
        no("unsigned expiry change REFUSED",
           wubu_pkgmgr_anchor_set_expiry_authorized(sign_pub, (int64_t)(now + 3600), NULL));
        no("unsigned expiry left no DB change",
           wubu_pkgmgr_anchor_expiry(sign_pub, NULL));
        /* NEGATIVE CONTROL: pre-change raw setter accepts the SAME unsigned
         * change; use a separate key so the real anchor stays untouched. */
        yes("pre-change raw setter ACCEPTS unsigned expiry (negative control)",
            legacy_set_expiry(wrong_pub, (int64_t)(now + 7200)));
        int64_t nc_exp = 0;
        yes("negative-control key now has expiry metadata",
            wubu_pkgmgr_anchor_expiry(wrong_pub, &nc_exp) && nc_exp == (int64_t)(now + 7200));
        yes("clean up negative-control expiry", legacy_set_expiry(wrong_pub, 0));

        yes("build signed future-expiry command",
            sign_expiry(sign_pub, (int64_t)(now + 3600), new_seed, sig, sizeof(sig)));
        yes("signed future expiry ACCEPTED",
            wubu_pkgmgr_anchor_set_expiry_authorized(sign_pub, (int64_t)(now + 3600), sig));
        yes("unexpired anchor VERIFIES", wubu_pkgmgr_verify_against_repos(pkg));
        yes("unexpired anchor allows dry-run install", wubu_pkgmgr_install(pkg, true));

        yes("sign wrong-key past expiry",
            sign_expiry(sign_pub, (int64_t)(now - 3600), wrong_seed, sig, sizeof(sig)));
        no("wrong-key expiry change REFUSED",
           wubu_pkgmgr_anchor_set_expiry_authorized(sign_pub, (int64_t)(now - 3600), sig));
        yes("wrong-key expiry left original metadata",
            wubu_pkgmgr_anchor_expiry(sign_pub, &got_exp_probe) &&
            got_exp_probe == (int64_t)(now + 3600));

        yes("build signed past-expiry command",
            sign_expiry(sign_pub, (int64_t)(now - 3600), new_seed, sig, sizeof(sig)));
        yes("signed past expiry ACCEPTED",
            wubu_pkgmgr_anchor_set_expiry_authorized(sign_pub, (int64_t)(now - 3600), sig));
        int64_t got_exp = 0;
        yes("expiry metadata readable",
            wubu_pkgmgr_anchor_expiry(sign_pub, &got_exp) && got_exp == (int64_t)(now - 3600));
        yes("anchor reported expired", wubu_pkgmgr_anchor_is_expired(sign_pub));
        /* NEGATIVE CONTROL: the pre-change expiry-blind verifier still
         * accepts this very package; only the new policy refuses it. */
        yes("pre-change verifier ACCEPTS expired anchor (negative control)",
            legacy_verify_against_repos(pkg));
        no("post-change verifier REFUSES expired anchor",
           wubu_pkgmgr_verify_against_repos(pkg));
        no("post-change install REFUSES expired anchor", wubu_pkgmgr_install(pkg, true));
        /* Leave the DB in the expired state for the fresh-process check. */

        /* ---------------- 4. Escrow lost-admin recovery ---------------- */
        printf("[gate] --- escrow lost-admin recovery ---\n");
        const char *escrow_members[2] = { q1_pub, q2_pub };
        yes("escrow command string built",
            wubu_pkgmgr_escrow_command_string(2, 2, escrow_members, cmd, sizeof(cmd)));
        no("1-of-2 escrow command rejected (M must be >= 2)",
           wubu_pkgmgr_escrow_command_string(1, 2, escrow_members, cmd, sizeof(cmd)));
        yes("rebuild valid escrow command",
            wubu_pkgmgr_escrow_command_string(2, 2, escrow_members, cmd, sizeof(cmd)));
        no("unsigned escrow config REFUSED",
           wubu_pkgmgr_escrow_configure(2, 2, escrow_members, NULL));
        yes("sign escrow config with current admin",
            sign_command(cmd, new_seed, sig, sizeof(sig)));
        yes("configure 2-of-2 escrow set",
            wubu_pkgmgr_escrow_configure(2, 2, escrow_members, sig));
        int em = 0, en = 0;
        yes("escrow status is 2-of-2",
            wubu_pkgmgr_escrow_status(&em, &en) && em == 2 && en == 2);
        no("duplicate-member escrow rejected",
           wubu_pkgmgr_escrow_command_string(2, 2,
                (const char *[]){ q1_pub, q1_pub }, cmd, sizeof(cmd)));

        yes("build escrow recovery command for rec_pub",
            wubu_pkgmgr_escrow_recovery_command_string(rec_pub, cmd, sizeof(cmd)));
        char e1[129], e2[129], ew[129];
        yes("sign recovery with escrow member 1", sign_command(cmd, q1_seed, e1, sizeof(e1)));
        yes("sign recovery with escrow member 2", sign_command(cmd, q2_seed, e2, sizeof(e2)));
        yes("sign recovery with WRONG key", sign_command(cmd, wrong_seed, ew, sizeof(ew)));
        const char *one_e[1] = { e1 };
        const char *wrong_e[1] = { ew };
        const char *mixed_e[2] = { e1, ew };
        const char *two_e[2] = { e1, e2 };
        no("1-of-2 escrow recovery REFUSED",
           wubu_pkgmgr_key_admin_recover(rec_pub, one_e, 1));
        no("wrong-key escrow recovery REFUSED",
           wubu_pkgmgr_key_admin_recover(rec_pub, wrong_e, 1));
        no("one valid + one wrong escrow sig REFUSED",
           wubu_pkgmgr_key_admin_recover(rec_pub, mixed_e, 2));
        yes("admin unchanged after refused recoveries", admin_is(new_pub));
        yes("2-of-2 escrow recovery ACCEPTED",
            wubu_pkgmgr_key_admin_recover(rec_pub, two_e, 2));
        yes("admin is now the recovered key", admin_is(rec_pub));

        /* Old admin key must lose ALL authority after recovery. */
        yes("build revoke command for old-admin test",
            wubu_pkgmgr_key_command_string("revoke", target, cmd, sizeof(cmd)));
        yes("sign revoke with PRE-recovery admin",
            sign_command(cmd, new_seed, sig, sizeof(sig)));
        no("old admin key REFUSED after recovery",
           wubu_pkgmgr_key_revoke_authorized(target, sig));
        no("old-key revoke left no revocation", wubu_pkgmgr_key_is_revoked(target));
        yes("sign revoke with recovered admin",
            sign_command(cmd, rec_seed, sig, sizeof(sig)));
        yes("recovered admin authorizes revoke",
            wubu_pkgmgr_key_revoke_authorized(target, sig));
        yes("recovered-admin revocation persisted", wubu_pkgmgr_key_is_revoked(target));
        yes("build unrevoke with recovered admin",
            wubu_pkgmgr_key_command_string("unrevoke", target, cmd, sizeof(cmd)));
        yes("sign unrevoke with recovered admin",
            sign_command(cmd, rec_seed, sig, sizeof(sig)));
        yes("clean target with recovered admin",
            wubu_pkgmgr_key_unrevoke_authorized(target, sig));

    } else if (strcmp(mode, "check") == 0) {
        printf("[gate] --- fresh process: reload policy from DB ---\n");
        yes("recovered admin persisted across restart", admin_is(rec_pub));
        yes("build revoke command with ORIGINAL admin signature",
            wubu_pkgmgr_key_command_string("revoke", target, cmd, sizeof(cmd)) &&
            sign_command(cmd, admin_seed, sig, sizeof(sig)));
        no("original admin still does not authorize after restart",
           wubu_pkgmgr_key_revoke_authorized(target, sig));
        yes("sign revoke with PRE-recovery admin key",
            sign_command(cmd, new_seed, sig, sizeof(sig)));
        no("pre-recovery admin still refused after restart",
           wubu_pkgmgr_key_revoke_authorized(target, sig));
        int qm = 0, qn = 0;
        yes("quorum 2-of-2 reloaded",
            wubu_pkgmgr_key_quorum_status(&qm, &qn) && qm == 2 && qn == 2);
        int em = 0, en = 0;
        yes("escrow 2-of-2 reloaded",
            wubu_pkgmgr_escrow_status(&em, &en) && em == 2 && en == 2);
        int64_t got_exp = 0;
        yes("expiry metadata reloaded from DB",
            wubu_pkgmgr_anchor_expiry(sign_pub, &got_exp) && got_exp > 0);
        yes("expired anchor still expired after reload",
            wubu_pkgmgr_anchor_is_expired(sign_pub));
        set_anchor(sign_pub);
        yes("signature itself remains valid (negative control)",
            wubu_pkgmgr_verify_package(pkg, sign_pub));
        yes("pre-change verifier ACCEPTS (negative control)",
            legacy_verify_against_repos(pkg));
        no("post-change verifier still REFUSES reloaded expired anchor",
           wubu_pkgmgr_verify_against_repos(pkg));
        /* Recovery: un-expire with the RECOVERED admin's signature. */
        no("unsigned clear-expiry REFUSED after restart",
           wubu_pkgmgr_anchor_set_expiry_authorized(sign_pub, 0, NULL));
        yes("expiry unchanged after unsigned clear",
            wubu_pkgmgr_anchor_is_expired(sign_pub));
        yes("sign clear-expiry with recovered admin",
            sign_expiry(sign_pub, 0, rec_seed, sig, sizeof(sig)));
        yes("clear expiry (signed recovery)",
            wubu_pkgmgr_anchor_set_expiry_authorized(sign_pub, 0, sig));
        yes("unexpired anchor verifies again after reload",
            wubu_pkgmgr_verify_against_repos(pkg));
        yes("unexpired anchor allows install again", wubu_pkgmgr_install(pkg, true));
    } else {
        fprintf(stderr, "[gate] unknown mode: %s\n", mode);
        return 2;
    }

    printf("[gate][%s] %d passed, %d failed\n", mode, passes, fails);
    return fails ? 1 : 0;
}
