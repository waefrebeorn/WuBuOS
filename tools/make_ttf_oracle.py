#!/usr/bin/env python3
"""make_ttf_oracle.py -- generate the TrueType reader's expected values from FreeType.

The oracle must be foreign. Pillow's ImageFont wraps FreeType, so the numbers in the generated
header come from a completely different implementation than src/runtime/wubu_truetype.c. If our
reader and this file ever disagree, one of them is wrong and the gate says so.

Advance widths are compared in whole pixels with a 1 px tolerance: FreeType returns fractional
pen advances and rounds at draw time, so an exact match would be testing rounding policy rather
than font parsing.

usage: python3 tools/make_ttf_oracle.py > tests/fixtures/ttf_oracle.h
"""
import sys

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
PPEMS = (13, 20)

CPS = list(range(0x20, 0x7F)) + [
    0x00A0, 0x00C0, 0x00E9, 0x00FC, 0x0100, 0x017F, 0x0391, 0x03B1, 0x0416, 0x05D0,
    0x20AC, 0x2190, 0x2192, 0x2260, 0x25A0, 0xFB01,
]


RASTER_CPS = [0x41, 0x6F, 0xE9, 0x67, 0x57, 0x4D]
RASTER_PPEMS = (13, 20, 48)


def emit_raster(out):
    """Expected ink bbox and mass from FreeType, for the coverage comparison.

    FreeType hints by default, so the shapes are not identical to an unhinted outline; the gate
    therefore compares ink MASS with a measured tolerance and the bbox within a few pixels,
    rather than pretending two different rasterisers produce equal pixels.
    """
    from PIL import ImageFont
    out.write("typedef struct { unsigned cp; int ppem; int w, h; long mass; } TtfRasterRow;\n\n")
    out.write("static const TtfRasterRow TTF_RASTER[] = {\n")
    n = 0
    for ppem in RASTER_PPEMS:
        f = ImageFont.truetype(FONT, ppem)
        for cp in RASTER_CPS:
            try:
                m = f.getmask(chr(cp), mode="L")
            except Exception:
                continue
            out.write("    { 0x%04X, %d, %d, %d, %d },\n" % (cp, ppem, m.size[0], m.size[1], sum(m)))
            n += 1
    out.write("};\n\n#define TTF_RASTER_N %d\n\n" % n)


def main():
    from PIL import ImageFont

    fonts = {p: ImageFont.truetype(FONT, p) for p in PPEMS}
    rows = []
    for cp in CPS:
        try:
            ch = chr(cp)
            widths = [fonts[p].getlength(ch) for p in PPEMS]
        except Exception:
            continue
        if all(w > 0 for w in widths):
            rows.append((cp, widths))

    out = sys.stdout
    out.write("/* generated by tools/make_ttf_oracle.py -- do not edit, do not hand-tune.\n"
              " * Expected advances come from FreeType via Pillow, never from our reader. */\n")
    out.write("#ifndef WUBU_TTF_ORACLE_H\n#define WUBU_TTF_ORACLE_H\n\n")
    fmt = ", ".join("%d" for _ in PPEMS)
    out.write("static const int TTF_ORACLE_PPEM[] = { %s };\n" % fmt % PPEMS)
    out.write("#define TTF_ORACLE_NPPEM %d\n\n" % len(PPEMS))
    out.write("typedef struct { unsigned cp; double adv[%d]; } TtfOracleRow;\n\n" % len(PPEMS))
    out.write("static const TtfOracleRow TTF_ORACLE[] = {\n")
    for cp, widths in rows:
        vals = ", ".join("%.3f" % w for w in widths)
        out.write("    { 0x%04X, { %s } },\n" % (cp, vals))
    out.write("};\n\n#define TTF_ORACLE_N %d\n\n" % len(rows))
    out.write('#define TTF_ORACLE_PATH "%s"\n\n' % FONT)
    emit_raster(out)
    out.write("#endif /* WUBU_TTF_ORACLE_H */\n")
    sys.stderr.write("oracle: %d code points, %d ppem\n" % (len(rows), len(PPEMS)))


if __name__ == "__main__":
    main()
