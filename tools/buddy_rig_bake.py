#!/usr/bin/env python3
"""Bake the canonical WuBu Buddy rig into a C11 header.

Emits src/runtime/wubu_buddy_rig_data.h containing:
  - kBuddyPalette : u32 RGBA palette
  - kBuddyIdx     : u8[W*H] palette index per pixel (0xFF = transparent)
  - kBuddyParts[] : per-part rect + pixel-offset list (the rig's joints)

The parts form a FULL-COVERAGE PARTITION of the opaque sprite: every opaque
pixel is owned by exactly one part, so drawing all parts reproduces the base
sprite exactly and any subset can be moved independently (the rig). Bands are
horizontal slices of the opaque bbox; arms are carved from the torso band's
outer columns and legs split at centre.

Anatomy mirrors tools/buddy_rig.py (chibi unibody).
"""
import os
from PIL import Image

SRC = "tools/assets/wubu_buddy_deck/canon_idle.png"
DST = "src/runtime/wubu_buddy_rig_data.h"
W = H = 96

# horizontal bands as fractions of the OPAQUE bbox height (full width)
BANDS = [("ears", 0.00, 0.22), ("cap", 0.22, 0.32), ("head", 0.32, 0.50),
         ("torso", 0.50, 0.78), ("legs", 0.78, 1.00)]
ARM_EDGE = 0.24          # outer fraction of the torso band carved as arms
PART_ORDER = ["ears", "cap", "head", "torso", "armL", "armR", "legL", "legR"]

def main():
    im = Image.open(SRC).convert("RGBA").resize((W, H), Image.NEAREST)
    px = im.load()
    idx = [0xFF] * (W * H)
    cols = {}
    for y in range(H):
        for x in range(W):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            key = (r << 24) | (g << 16) | (b << 8) | 0xFF
            if key not in cols:
                cols[key] = len(cols)
            idx[y * W + x] = cols[key]
    pal = sorted(cols.items(), key=lambda kv: kv[1])

    xs = [x for y in range(H) for x in range(W) if idx[y * W + x] != 0xFF]
    ys = [y for y in range(H) for x in range(W) if idx[y * W + x] != 0xFF]
    x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)
    bw, bh = x1 - x0 + 1, y1 - y0 + 1

    # ---- partition: each opaque pixel -> exactly one part ----
    plist = {k: [] for k in PART_ORDER}
    for y in range(y0, y1 + 1):
        fy = (y - y0) / float(bh)
        band = None
        for name, lo, hi in BANDS:
            if lo <= fy < hi or (name == "legs" and fy >= lo):
                band = name
                break
        for x in range(x0, x1 + 1):
            off = y * W + x
            if idx[off] == 0xFF:
                continue
            fx = (x - x0) / float(bw)
            if band == "torso":
                part = "armL" if fx < ARM_EDGE else ("armR" if fx > 1 - ARM_EDGE else "torso")
            elif band == "legs":
                part = "legL" if fx < 0.5 else "legR"
            else:
                part = band
            plist[part].append(off)

    # tight rect per part (bbox of its pixels)
    parts = []
    for name in PART_ORDER:
        ps = plist[name]
        if not ps:
            continue
        pxs = [p % W for p in ps]; pys = [p // W for p in ps]
        parts.append((name, min(pxs), min(pys), max(pxs) - min(pxs) + 1,
                      max(pys) - min(pys) + 1, ps))

    # ---- emit ----
    L = []
    A = L.append
    A("/* Generated by tools/buddy_rig_bake.py -- do not edit. */")
    A("#ifndef WUBU_BUDDY_RIG_DATA_H")
    A("#define WUBU_BUDDY_RIG_DATA_H")
    A("#include <stdint.h>")
    A("")
    A(f"#define BUDDY_W {W}")
    A(f"#define BUDDY_H {H}")
    A(f"#define BUDDY_PAL_N {len(pal)}")
    A(f"#define BUDDY_PART_N {len(parts)}")
    A("")
    A("static const uint32_t kBuddyPalette[BUDDY_PAL_N] = {")
    row = []
    for key, _ in pal:
        r = (key >> 24) & 255; g = (key >> 16) & 255; b = (key >> 8) & 255
        row.append(f"0x{r:02X}{g:02X}{b:02X}FFu")
        if len(row) == 8:
            A("    " + ", ".join(row) + ","); row = []
    if row:
        A("    " + ", ".join(row) + ",")
    A("};")
    A("")
    A("/* u8 palette index per pixel; 0xFF = transparent. */")
    A(f"static const uint8_t kBuddyIdx[BUDDY_W*BUDDY_H] = {{")
    for y in range(H):
        A("    " + ", ".join(str(v) for v in idx[y * W:(y + 1) * W]) + ",")
    A("};")
    A("")
    A("typedef struct {")
    A("    const char *name;")
    A("    uint8_t x, y, w, h;      /* rect inside the 96x96 cell */")
    A("    uint16_t n;              /* pixel count */")
    A("    const uint16_t *px;      /* pixel offsets into kBuddyIdx */")
    A("} wubu_buddy_part_def_t;")
    A("")
    for name, rx, ry, rw, rh, ps in parts:
        A(f"static const uint16_t kBuddyPx_{name}[{len(ps)}] = {{")
        for j in range(0, len(ps), 24):
            A("    " + ", ".join(str(v) for v in ps[j:j + 24]) + ",")
        A("};")
    A("")
    A("static const wubu_buddy_part_def_t kBuddyParts[BUDDY_PART_N] = {")
    for name, rx, ry, rw, rh, ps in parts:
        A(f'    {{"{name}", {rx}, {ry}, {rw}, {rh}, {len(ps)}, kBuddyPx_{name}}},')
    A("};")
    A("")
    A("#endif /* WUBU_BUDDY_RIG_DATA_H */")

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"{DST}: palette={len(pal)} parts={[p[0] for p in parts]} "
          f"opaque={sum(len(p[5]) for p in parts)} bytes~{os.path.getsize(DST)//1024}KB")

if __name__ == "__main__":
    main()