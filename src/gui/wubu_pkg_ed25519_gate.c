/* wubu_pkg_ed25519_gate.c -- opt-in differential gate harness.
 * Built only by tools/pkg_ed25519_gate.sh with WUBU_HAVE_MBEDTLS.
 *
 * Two invocations share one on-disk pkgmgr DB:
 *   record: create a genuinely signed package, prove it verifies AND installs,
 *           then persist a revocation of its trust anchor to the DB.
 *   check:  a FRESH process reloads the revocation from that DB and must
 *           refuse verification AND install of the same still-valid package;
 *           rotating to a new key restores both; revoking the new key too
 *           fails closed even though an anchor is still configured.
 * Keys are ephemeral (generated by the shell driver); no key material is
 * ever written into the repository.
 */
#include "wubu_pkgmgr.h"
#include "wubu_pkgmgr_internal.h"
#include "wubu_pkg_sign.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

static uint8_t *slurp(const char *path, size_t *len) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }
    long n = ftell(f);
    rewind(f);
    if (n <= 0) { fclose(f); return NULL; }
    uint8_t *buf = (uint8_t *)malloc((size_t)n);
    if (!buf) { fclose(f); return NULL; }
    if (fread(buf, 1, (size_t)n, f) != (size_t)n) { free(buf); fclose(f); return NULL; }
    fclose(f);
    *len = (size_t)n;
    return buf;
}

static bool spill(const char *path, const uint8_t *buf, size_t len) {
    FILE *f = fopen(path, "wb");
    if (!f) return false;
    size_t w = fwrite(buf, 1, len, f);
    fclose(f);
    return w == len;
}

/* Exact FNV-1a placeholder from the pre-Ed25519 writer, for the negative
 * control: a hash-shaped signature must NOT be accepted as Ed25519. */
static void legacy_fnv_signature(const uint8_t *hdr, size_t sig_off,
                                 const uint8_t *manifest, size_t mlen,
                                 const uint8_t *payload, size_t plen,
                                 uint32_t crc, uint8_t out[64]) {
    uint64_t hash = 0xcbf29ce484222325ULL;
    for (size_t i = 0; i < sig_off; i++) { hash ^= hdr[i]; hash *= 0x100000001b3ULL; }
    for (size_t i = 0; i < mlen; i++) { hash ^= manifest[i]; hash *= 0x100000001b3ULL; }
    for (size_t i = 0; i < plen; i++) { hash ^= payload[i]; hash *= 0x100000001b3ULL; }
    memcpy(out, &hash, sizeof(hash));
    hash ^= (uint64_t)crc;
    hash *= 0x100000001b3ULL;
    memcpy(out + 8, &hash, sizeof(hash));
    for (int i = 16; i < 64; i++)
        out[i] = (uint8_t)(hash >> ((i % 8) * 8)) ^ (uint8_t)i;
}

/* VERBATIM pre-change policy from HEAD (wubu_pkgmgr_install.c).  Negative
 * control: if this still verifies a revoked key, the new refusal is caused
 * by the revocation policy, not by a broken signature or a bad package. */
static bool legacy_verify_against_repos(const char *pkg_path) {
    for (int i = 0; i < g_pkgmgr.n_repos; i++)
        if (g_pkgmgr.repos[i].enabled && g_pkgmgr.repos[i].pubkey[0] &&
            wubu_pkgmgr_verify_package(pkg_path, g_pkgmgr.repos[i].pubkey))
            return true;
    return false;
}

static int expect(const char *label, bool got, bool want) {
    bool pass = got == want;
    printf("[gate] %-48s %s (result %s)\n", label,
           pass ? "PASS" : "FAIL", got ? "true" : "false");
    return pass ? 0 : 1;
}

static void set_anchor(const char *pub) {
    memset(g_pkgmgr.repos, 0, sizeof(g_pkgmgr.repos));
    g_pkgmgr.n_repos = 1;
    g_pkgmgr.repos[0].enabled = true;
    snprintf(g_pkgmgr.repos[0].pubkey, sizeof(g_pkgmgr.repos[0].pubkey), "%s", pub);
}

static wubu_pkg_manifest_t gate_manifest(void) {
    wubu_pkg_manifest_t m;
    memset(&m, 0, sizeof(m));
    snprintf(m.id, sizeof(m.id), "ed25519-gate");
    snprintf(m.name, sizeof(m.name), "Ed25519 Gate App");
    snprintf(m.version, sizeof(m.version), "1.0.0");
    snprintf(m.description, sizeof(m.description), "differential signature gate");
    snprintf(m.license, sizeof(m.license), "MIT");
    m.arch = WUBU_PKG_ARCH_X86_64;
    m.payload_type = WUBU_PKG_PAYLOAD_DATA;
    snprintf(m.sandbox_profile, sizeof(m.sandbox_profile), "default");
    snprintf(m.files[0].src, sizeof(m.files[0].src), "payload.txt");
    snprintf(m.files[0].dst, sizeof(m.files[0].dst), "payload.txt");
    m.files[0].mode = 0644;
    m.n_files = 1;
    return m;
}

/* Returns the number of failed crypto-differential checks on a signed pkg. */
static int crypto_differentials(const char *pkg, const char *pub,
                                const char *wrong_pub, const char *srcdir,
                                const char *seed, const wubu_pkg_manifest_t *m) {
    int fails = 0;
    size_t hdr_len = sizeof(wubu_pkg_header_t);
    size_t sig_off = offsetof(wubu_pkg_header_t, signature);

    fails += expect("bad seed rejected at sign",
                    wubu_pkgmgr_create_package(srcdir, "/tmp/wubu_bad_seed.wubu",
                                               m, "deadbeef"), false);
    remove("/tmp/wubu_bad_seed.wubu");

    if (!wubu_pkgmgr_create_package(srcdir, pkg, m, seed)) {
        fprintf(stderr, "[gate] FAIL: could not create a signed package\n");
        return 1;
    }
    printf("[gate] created signed package: %s\n", pkg);

    fails += expect("valid signed package", wubu_pkgmgr_verify_package(pkg, pub), true);

    size_t total = 0;
    uint8_t *orig = slurp(pkg, &total);
    if (!orig || total < hdr_len + 16) {
        fprintf(stderr, "[gate] FAIL: cannot read package\n");
        return 1;
    }
    wubu_pkg_header_t *h = (wubu_pkg_header_t *)orig;
    size_t m_off = hdr_len, p_off = hdr_len + h->manifest_size;
    size_t m_len = h->manifest_size, p_len = total - p_off;

    /* Tampered payload. */
    {
        uint8_t *t = (uint8_t *)malloc(total);
        memcpy(t, orig, total);
        t[p_off + 16] ^= 0x5a;
        if (!spill(pkg, t, total)) return 1;
        fails += expect("tampered payload rejected", wubu_pkgmgr_verify_package(pkg, pub), false);
        free(t);
    }
    /* Tampered signature. */
    {
        uint8_t *t = (uint8_t *)malloc(total);
        memcpy(t, orig, total);
        t[sig_off + 7] ^= 0x01;
        if (!spill(pkg, t, total)) return 1;
        fails += expect("tampered signature rejected", wubu_pkgmgr_verify_package(pkg, pub), false);
        free(t);
    }
    /* Negative control: old FNV placeholder is not an Ed25519 signature. */
    {
        uint8_t *t = (uint8_t *)malloc(total);
        memcpy(t, orig, total);
        memset(t + sig_off, 0, WUBU_PKG_SIG_SIZE);
        legacy_fnv_signature(t, sig_off, t + m_off, m_len,
                             t + p_off, p_len, h->crc32, t + sig_off);
        if (!spill(pkg, t, total)) return 1;
        fails += expect("negative control: legacy FNV rejected",
                        wubu_pkgmgr_verify_package(pkg, pub), false);
        free(t);
    }
    /* Unsigned package. */
    {
        uint8_t *t = (uint8_t *)malloc(total);
        memcpy(t, orig, total);
        memset(t + sig_off, 0, WUBU_PKG_SIG_SIZE);
        if (!spill(pkg, t, total)) return 1;
        fails += expect("unsigned package rejected", wubu_pkgmgr_verify_package(pkg, pub), false);
        free(t);
    }

    if (!spill(pkg, orig, total)) return 1;
    fails += expect("missing trust anchor rejected", wubu_pkgmgr_verify_package(pkg, NULL), false);
    fails += expect("wrong public key rejected", wubu_pkgmgr_verify_package(pkg, wrong_pub), false);

    /* Small-subgroup forgery (identity public key). */
    {
        char small_pub[65];
        small_pub[0] = '0'; small_pub[1] = '1';
        memset(small_pub + 2, '0', 62);
        small_pub[64] = '\0';
        uint8_t *t = (uint8_t *)malloc(total);
        if (!t) return 1;
        memcpy(t, orig, total);
        static const uint8_t base_enc[32] = {
            0x58,0x66,0x66,0x66,0x66,0x66,0x66,0x66,
            0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,
            0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,
            0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66
        };
        memset(t + sig_off, 0, WUBU_PKG_SIG_SIZE);
        memcpy(t + sig_off, base_enc, 32);
        t[sig_off + 32] = 1;
        if (!spill(pkg, t, total)) return 1;
        fails += expect("small-subgroup public key rejected",
                        wubu_pkgmgr_verify_package(pkg, small_pub), false);
        if (!spill(pkg, orig, total)) return 1;
        free(t);
    }

    fails += expect("pristine package still verifies", wubu_pkgmgr_verify_package(pkg, pub), true);

    /* Every enabled repo key is tried, not just the first. */
    memset(g_pkgmgr.repos, 0, sizeof(g_pkgmgr.repos));
    g_pkgmgr.n_repos = 2;
    g_pkgmgr.repos[0].enabled = true;
    snprintf(g_pkgmgr.repos[0].pubkey, sizeof(g_pkgmgr.repos[0].pubkey), "%s", wrong_pub);
    g_pkgmgr.repos[1].enabled = true;
    snprintf(g_pkgmgr.repos[1].pubkey, sizeof(g_pkgmgr.repos[1].pubkey), "%s", pub);
    fails += expect("second repo trust anchor verifies",
                    wubu_pkgmgr_verify_against_repos(pkg), true);
    snprintf(g_pkgmgr.repos[1].pubkey, sizeof(g_pkgmgr.repos[1].pubkey), "%s", wrong_pub);
    fails += expect("no matching trust anchor rejected",
                    wubu_pkgmgr_verify_against_repos(pkg), false);
    g_pkgmgr.n_repos = 0;

    free(orig);
    return fails;
}

int main(int argc, char **argv) {
    if (argc < 10) {
        fprintf(stderr, "usage: %s <record|check> <dbdir> <pkg> <srcdir> "
                        "<seed> <pub> <wrong_pub> <rot_seed> <rot_pub>\n", argv[0]);
        return 2;
    }
    const char *mode = argv[1], *dbdir = argv[2], *pkg = argv[3], *srcdir = argv[4];
    const char *seed = argv[5], *pub = argv[6], *wrong_pub = argv[7];
    const char *rot_seed = argv[8], *rot_pub = argv[9];

    wubu_pkgmgr_config_t cfg;
    wubu_pkgmgr_get_default_config(&cfg);
    snprintf(cfg.db_path, sizeof(cfg.db_path), "%s", dbdir);
    char path[512];
    snprintf(path, sizeof(path), "%s/cache", dbdir);
    snprintf(cfg.cache_dir, sizeof(cfg.cache_dir), "%s", path);
    snprintf(path, sizeof(path), "%s/prefix", dbdir);
    snprintf(cfg.install_prefix, sizeof(cfg.install_prefix), "%s", path);
    snprintf(path, sizeof(path), "%s/repos", dbdir);
    snprintf(cfg.repo_config_dir, sizeof(cfg.repo_config_dir), "%s", path);

    if (!wubu_pkgmgr_init(&cfg)) {
        fprintf(stderr, "[gate] FAIL: pkgmgr init (revocation reload) failed\n");
        return 1;
    }
    wubu_pkg_manifest_t m = gate_manifest();
    int fails = 0;

    if (strcmp(mode, "record") == 0) {
        char upper[65];
        snprintf(upper, sizeof(upper), "%s", pub);
        for (size_t i = 0; i < strlen(upper); i++)
            upper[i] = (char)toupper((unsigned char)upper[i]);
        fails += expect("revoke rejects malformed hex",
                        wubu_pkgmgr_key_revoke("deadbeef"), false);
        fails += expect("revoke rejects uppercase hex",
                        wubu_pkgmgr_key_revoke(upper), false);

        fails += crypto_differentials(pkg, pub, wrong_pub, srcdir, seed, &m);

        /* Genuine key: verification AND the real install path accept it. */
        set_anchor(pub);
        fails += expect("valid package verifies via repo anchor",
                        wubu_pkgmgr_verify_against_repos(pkg), true);
        fails += expect("install accepts genuine package (dry run)",
                        wubu_pkgmgr_install(pkg, true), true);

        /* Persist the revocation of that anchor to the DB. */
        fails += expect("revoke key persisted to DB",
                        wubu_pkgmgr_key_revoke(pub), true);
        fails += expect("revocation visible in process cache",
                        wubu_pkgmgr_key_is_revoked(pub), true);
        fails += expect("revoke is idempotent",
                        wubu_pkgmgr_key_revoke(pub), true);
        fails += expect("revoked anchor refused by verifier",
                        wubu_pkgmgr_verify_against_repos(pkg), false);
        fails += expect("revoked anchor refused by install",
                        wubu_pkgmgr_install(pkg, true), false);
        printf("[gate][record] revocation persisted to %s/pkgmgr.db\n", dbdir);
    } else if (strcmp(mode, "check") == 0) {
        /* FRESH process: only the DB can carry the revocation state. */
        fails += expect("revocation reloaded in fresh process",
                        wubu_pkgmgr_key_is_revoked(pub), true);
        fails += expect("revoked count reloaded from DB",
                        wubu_pkgmgr_key_revoked_count() == 1, true);

        set_anchor(pub);
        fails += expect("signature itself still valid (negative control)",
                        wubu_pkgmgr_verify_package(pkg, pub), true);
        fails += expect("pre-change policy accepts revoked key (negative control)",
                        legacy_verify_against_repos(pkg), true);
        fails += expect("post-change verifier refuses revoked key",
                        wubu_pkgmgr_verify_against_repos(pkg), false);
        fails += expect("post-change install refuses revoked key",
                        wubu_pkgmgr_install(pkg, true), false);

        /* Rotate to a new trust anchor and a package signed by its key. */
        char rot_pkg[512];
        snprintf(rot_pkg, sizeof(rot_pkg), "%s/rotated.wubu", dbdir);
        if (!wubu_pkgmgr_create_package(srcdir, rot_pkg, &m, rot_seed)) {
            fprintf(stderr, "[gate] FAIL: could not create rotated package\n");
            return 1;
        }
        set_anchor(rot_pub);
        fails += expect("rotated package verifies raw",
                        wubu_pkgmgr_verify_package(rot_pkg, rot_pub), true);
        fails += expect("rotated key verifies via repo anchor",
                        wubu_pkgmgr_verify_against_repos(rot_pkg), true);
        fails += expect("install accepts rotated key (dry run)",
                        wubu_pkgmgr_install(rot_pkg, true), true);
        fails += expect("old key no longer verified after rotation",
                        wubu_pkgmgr_verify_against_repos(pkg), false);

        /* Revoke the rotated key too: a configured anchor still fails closed. */
        fails += expect("revoke rotated key",
                        wubu_pkgmgr_key_revoke(rot_pub), true);
        fails += expect("all anchors revoked -> verifier fail closed",
                        wubu_pkgmgr_verify_against_repos(rot_pkg), false);
        fails += expect("all anchors revoked -> install fail closed",
                        wubu_pkgmgr_install(rot_pkg, true), false);

        /* Unrevoke restores verification and install. */
        set_anchor(pub);
        fails += expect("unrevoke old key",
                        wubu_pkgmgr_key_unrevoke(pub), true);
        fails += expect("unrevoked key verifies again",
                        wubu_pkgmgr_verify_against_repos(pkg), true);
        fails += expect("install accepts unrevoked key (dry run)",
                        wubu_pkgmgr_install(pkg, true), true);
        printf("[gate][check] reload -> refusal -> rotation -> recovery verified\n");
    } else {
        fprintf(stderr, "[gate] unknown mode: %s\n", mode);
        return 2;
    }

    printf("[gate][%s] %s (%d failure%s)\n", mode, fails ? "FAILED" : "ALL CHECKS PASSED",
           fails, fails == 1 ? "" : "s");
    return fails ? 1 : 0;
}
