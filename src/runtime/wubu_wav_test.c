int main(void) {
    printf("=== wubu_wav (slerm gate, SLERM-2017) ===\n");
    for (size_t i = 0; i < sizeof CASES / sizeof CASES[0]; i++) {
        const Case *c = &CASES[i];
        WubuWav info = {0};
        int err = 0;
        if (wubu_wav_info(c->file, c->flen, &info, &err) != 0) {
            printf("  [FAIL] %-12s info: %s\n", c->name, wubu_wav_reason(err)); fail++; continue;
        }
        if (info.channels != c->channels || info.sample_rate != c->rate || info.frames != c->frames) {
            printf("  [FAIL] %-12s info ch=%d rate=%d frames=%d want %d/%d/%d\n", c->name,
                   info.channels, info.sample_rate, info.frames, c->channels, c->rate, c->frames);
            fail++; continue;
        }
        float *out = malloc(sizeof(float) * (size_t)c->samples);
        if (wubu_wav_decode(c->file, c->flen, out, (size_t)c->samples, &info, &err) != 0) {
            printf("  [FAIL] %-12s decode: %s\n", c->name, wubu_wav_reason(err)); free(out); fail++; continue;
        }
        int good = 1;
        for (int k = 0; k < c->samples; k++)
            if (fabsf(out[k] - c->expect[k]) > 1e-6f) { good = 0; break; }
        if (good) pass++;
        else { printf("  [FAIL] %-12s sample mismatch (first %g want %g)\n", c->name, out[0], c->expect[0]); fail++; }
        free(out);
    }

    {
        enum { N = 256 };
        float src[N];
        for (int i = 0; i < N; i++) src[i] = sinf((float)i * 0.05f) * 0.8f;
        unsigned char buf[44 + N * 2];
        int err = 0;
        long n = wubu_wav_encode_pcm16(src, N, 1, 22050, buf, sizeof buf, &err);
        if (n == (long)sizeof buf) pass++;
        else { printf("  [FAIL] encode size %ld\n", n); fail++; }
        WubuWav info; float back[N];
        if (wubu_wav_decode(buf, (size_t)(n > 0 ? n : 0), back, N, &info, &err) == 0 &&
            info.frames == N && info.sample_rate == 22050) pass++;
        else { printf("  [FAIL] encoded WAV does not decode\n"); fail++; }
        int good = 1;
        for (int i = 0; i < N; i++) if (fabsf(back[i] - src[i]) > (1.0f / 32767.0f) * 1.5f) good = 0;
        if (good) pass++; else { printf("  [FAIL] round trip exceeds one quantum\n"); fail++; }
    }

    {
        WubuWav info; int err = 0; float out[8];
        if (wubu_wav_decode(f_mulaw, sizeof f_mulaw, out, 8, &info, &err) != 0 && err == WUBU_WAV_UNSUPPORTED) pass++;
        else { printf("  [FAIL] mu-law accepted (err %d)\n", err); fail++; }
        static const unsigned char junk[] = { 'R','I','F','F',0,0,0,0,'A','V','I',' ',0,0,0,0 };
        err = 0;
        if (wubu_wav_decode(junk, sizeof junk, out, 8, &info, &err) != 0 && err == WUBU_WAV_FORMAT) pass++;
        else { printf("  [FAIL] non-WAVE accepted (err %d)\n", err); fail++; }
        err = 0;
        if (wubu_wav_decode(f_pcm16_mono, sizeof f_pcm16_mono, out, 4, &info, &err) != 0 && err == WUBU_WAV_OVERFLOW) pass++;
        else { printf("  [FAIL] undersized buffer accepted (err %d)\n", err); fail++; }
    }

    printf("\n=== %d passed, %d failed ===\n", pass, fail);
    return fail ? 1 : 0;
}
